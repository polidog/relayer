<?php

declare(strict_types=1);

namespace Polidog\Relayer\Router\Native;

/**
 * Renders the `relayer_main.go` that `relayer native:build` places next to
 * a user's `route.go` before compiling the two together.
 *
 * The user file declares only `func GET(w, r)` & co. — no `main()`, like
 * the Next.js prototype — so this is where the process gets one: it serves
 * exactly one request through the stdlib's `net/http/cgi`, switching on
 * the method to the declared handler and synthesizing the rest with the
 * same rules the PHP `route.php` dispatcher applies:
 *
 *  - undeclared `OPTIONS` → `204` + `Allow`;
 *  - undeclared `HEAD` with a `GET` → run `GET`, drop the body;
 *  - anything else undeclared → `405` + `Allow`, JSON body.
 *
 * An explicitly declared `HEAD` / `OPTIONS` always wins. Generated, never
 * hand-edited: the build regenerates it every time.
 */
final class GoEntrypoint
{
    public const FILE_NAME = 'relayer_main.go';

    /**
     * @param list<string> $declared the handler methods the route.go declares
     */
    public static function render(array $declared): string
    {
        $allow = \implode(', ', GoRouteFile::effectiveAllowedMethods($declared));
        $allowLiteral = self::goString($allow);

        $cases = [];
        foreach ($declared as $method) {
            $cases[] = \sprintf("\tcase %s:\n\t\t%s(w, r)", self::goString($method), $method);
        }
        if (!\in_array('HEAD', $declared, true) && \in_array('GET', $declared, true)) {
            $cases[] = "\tcase \"HEAD\":\n\t\tGET(headWriter{w}, r)";
        }
        if (!\in_array('OPTIONS', $declared, true)) {
            $cases[] = "\tcase \"OPTIONS\":\n\t\tw.Header().Set(\"Allow\", {$allowLiteral})\n\t\tw.WriteHeader(http.StatusNoContent)";
        }

        $switch = \implode("\n", $cases);

        return <<<GO
            // Code generated by `relayer native:build`. DO NOT EDIT.
            //
            // Entry point for the route.go beside this file: serves one request
            // as a CGI child (the PHP side starts this binary per request).
            package main

            import (
            	"net/http"
            	"net/http/cgi"
            )

            // headWriter discards the body so a synthesized HEAD answers with the
            // GET handler's status and headers only.
            type headWriter struct{ http.ResponseWriter }

            func (w headWriter) Write(b []byte) (int, error) { return len(b), nil }

            func relayerDispatch(w http.ResponseWriter, r *http.Request) {
            	switch r.Method {
            {$switch}
            	default:
            		w.Header().Set("Allow", {$allowLiteral})
            		w.Header().Set("Content-Type", "application/json; charset=utf-8")
            		w.WriteHeader(http.StatusMethodNotAllowed)
            		w.Write([]byte(`{"error":"Method Not Allowed"}`))
            	}
            }

            func main() {
            	if err := cgi.Serve(http.HandlerFunc(relayerDispatch)); err != nil {
            		panic(err)
            	}
            }

            GO;
    }

    /**
     * `go.mod` for a route that ships none of its own: stdlib only, so no
     * requirements. The `go` directive is the oldest release whose
     * `net/http/cgi` behaves as documented here; a newer local toolchain
     * builds it unchanged.
     */
    public static function renderGoMod(string $module): string
    {
        return "module {$module}\n\ngo 1.22\n";
    }

    private static function goString(string $value): string
    {
        return '"' . \addcslashes($value, "\"\\\n") . '"';
    }
}
