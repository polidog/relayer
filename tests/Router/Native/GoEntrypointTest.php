<?php

declare(strict_types=1);

namespace Polidog\Relayer\Tests\Router\Native;

use PHPUnit\Framework\TestCase;
use Polidog\Relayer\Router\Native\GoEntrypoint;

final class GoEntrypointTest extends TestCase
{
    public function testDispatchesDeclaredMethodsAndSynthesizesTheRest(): void
    {
        $go = GoEntrypoint::render(['GET', 'POST']);

        self::assertStringStartsWith('// Code generated by `relayer native:build`. DO NOT EDIT.', $go);
        self::assertStringContainsString('package main', $go);
        self::assertStringContainsString('"net/http/cgi"', $go);
        self::assertStringContainsString("case \"GET\":\n\t\tGET(w, r)", $go);
        self::assertStringContainsString("case \"POST\":\n\t\tPOST(w, r)", $go);
        // HEAD synthesized from GET with the body discarded.
        self::assertStringContainsString("case \"HEAD\":\n\t\tGET(headWriter{w}, r)", $go);
        // OPTIONS synthesized as 204 + Allow (declared + HEAD + OPTIONS, sorted).
        self::assertStringContainsString('case "OPTIONS":', $go);
        self::assertStringContainsString('w.Header().Set("Allow", "GET, HEAD, OPTIONS, POST")', $go);
        self::assertStringContainsString('w.Header()["Content-Type"] = nil', $go);
        self::assertStringContainsString('http.StatusMethodNotAllowed', $go);
        self::assertStringContainsString('{"error":"Method Not Allowed"}', $go);
        self::assertStringContainsString('cgi.Serve(http.HandlerFunc(relayerDispatch))', $go);
    }

    public function testExplicitHeadAndOptionsAreNotSynthesized(): void
    {
        $go = GoEntrypoint::render(['GET', 'HEAD', 'OPTIONS']);

        self::assertStringContainsString("case \"HEAD\":\n\t\tHEAD(w, r)", $go);
        self::assertStringContainsString("case \"OPTIONS\":\n\t\tOPTIONS(w, r)", $go);
        self::assertStringNotContainsString('headWriter{w}', $go);
        self::assertStringNotContainsString('http.StatusNoContent', $go);
        self::assertSame(1, \substr_count($go, 'case "HEAD":'));
        self::assertSame(1, \substr_count($go, 'case "OPTIONS":'));
    }

    public function testNoHeadWithoutGet(): void
    {
        $go = GoEntrypoint::render(['POST']);

        self::assertStringNotContainsString('case "HEAD":', $go);
        self::assertStringContainsString('w.Header().Set("Allow", "OPTIONS, POST")', $go);
    }

    public function testGoModIsStdlibOnly(): void
    {
        $mod = GoEntrypoint::renderGoMod('relayer_native_api__hello');

        self::assertSame("module relayer_native_api__hello\n\ngo 1.22\n", $mod);
    }

    public function testProxyEntrypointServesStraightThroughProxy(): void
    {
        $go = GoEntrypoint::renderProxy();

        self::assertStringStartsWith('// Code generated by `relayer native:build`. DO NOT EDIT.', $go);
        self::assertStringContainsString('package main', $go);
        self::assertStringContainsString('cgi.Serve(http.HandlerFunc(Proxy))', $go);
        self::assertStringNotContainsString('switch r.Method', $go);
    }
}
